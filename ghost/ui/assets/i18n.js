class I18nManager {
  constructor() {
    this.currentLang = this.detectLanguage();
  }

  detectLanguage() {
    const saved = localStorage.getItem("ghost_language");
    if (saved && I18N_TRANSLATIONS[saved]) return saved;

    const navLang = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    const primary = navLang.split("-")[0];
    if (I18N_TRANSLATIONS[primary]) return primary;
    return "en";
  }

  setLanguage(code) {
    if (!I18N_TRANSLATIONS[code]) code = "en";
    this.currentLang = code;
    localStorage.setItem("ghost_language", code);
    this.applyTranslations();

    if (window.pywebview && window.pywebview.api && window.pywebview.api.set_locale) {
      window.pywebview.api.set_locale(code).catch(() => {});
    }
  }

  t(key, fallback = "") {
    const dict = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS.en;
    return dict[key] !== undefined ? dict[key] : (I18N_TRANSLATIONS.en[key] || fallback || key);
  }

  getQuotes() {
    const dict = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS.en;
    return dict.quotes || I18N_TRANSLATIONS.en.quotes;
  }

  applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const text = this.t(key);
      if (text) el.innerText = text;
    });

    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      const key = el.getAttribute("data-i18n-ph");
      const text = this.t(key);
      if (text) el.setAttribute("placeholder", text);
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      const text = this.t(key);
      if (text) el.setAttribute("title", text);
    });

    const langSelect = document.getElementById("lang-select");
    if (langSelect && langSelect.value !== this.currentLang) {
      langSelect.value = this.currentLang;
    }
  }
}

const i18n = new I18nManager();
